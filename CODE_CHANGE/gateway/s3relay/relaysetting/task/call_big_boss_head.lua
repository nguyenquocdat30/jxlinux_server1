function MAKE_NEW_BIG_BOSS(nNumBoss)
	if not nNumBoss then
	return
	end
	for k = 1,nNumBoss do
	local i = random(1,getn(BIG_BOSS_INFO));
		bossname = BIG_BOSS_INFO[i][1]
		bossid = BIG_BOSS_INFO[i][2]
		bosslvl = BIG_BOSS_INFO[i][3]
		series = BIG_BOSS_INFO[i][4]
		szMap = BIG_BOSS_INFO[i][5][random(1,getn(BIG_BOSS_INFO[i][5]))]
		world, posx, posy, worldname = GET_BIG_BOSS_POS(szMap)
		toadox = floor(posx/8)
		toadoy=floor(posy/16)
		sNews = format("Giang hå truyÒn r»ng %s ®· xuÊt hiÖn t¹i <color=yellow>%s<color> vâ l©m trung nguyªn sÏ cã mét cuéc chiÕn ®Èm m¸u!",bossname, worldname);
		sMsg = format("<color=green><color=yellow> %s <color>xuÊt hiÖn t¹i\n            <color=yellow>%s (%s/%s)<color><color>",bossname,worldname,toadox,toadoy);
		GlobalExecute(format("dw AddLocalNews([[%s]])", sNews));	
		GlobalExecute(format("dw Msg2SubWorld([[%s]])", sMsg));	
		GlobalExecute(format("dw CALL_NEW_BIG_BOSS(%d, %d, %d, %d, %d, %d, [[%s]])",bossid, bosslvl, series, world, posx, posy, bossname));
		OutputMsg("CALL_BIG_BOSS "..bossname..",,"..world..","..posx..","..posy..","..date("----%Y/%m/%d -%H:%M"))
	end
end

function GET_BIG_BOSS_POS(szMap)
	local cityidx = random(getn(BIG_BOSS_POS[szMap]))
	local posidx = random(1,getn(BIG_BOSS_POS[szMap][cityidx][2]));
	local world = BIG_BOSS_POS[szMap][cityidx][1]
	local posx = BIG_BOSS_POS[szMap][cityidx][2][posidx][1]
	local posy = BIG_BOSS_POS[szMap][cityidx][2][posidx][2]
	return world, posx, posy, BIG_BOSS_POS[szMap][cityidx][3]
end

